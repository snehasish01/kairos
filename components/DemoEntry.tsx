"use client";

import { useState } from "react";
import { enterDemo, randomDemoCondition } from "@/lib/demo/client";
import type { DemoCondition } from "@/lib/demo/shared";

type Choice = DemoCondition | "random";

const CHOICES: { value: Choice; label: string; blurb: string }[] = [
  { value: "anticipatory", label: "Anticipatory",
    blurb: "The reflection question can appear while you explore, if your activity suggests your position is forming." },
  { value: "reactive",     label: "Reactive",
    blurb: "The reflection question appears right after you click “I've reached my position”." },
  { value: "random",       label: "Pick one for me",
    blurb: "Your browser picks one of the two at random." },
];

/** Shown on /onboard when there are no Prolific parameters (the study is closed). */
export default function DemoEntry({ onStarted }: { onStarted: () => void }) {
  const [choice,   setChoice]   = useState<Choice>("random");
  const [starting, setStarting] = useState(false);
  const [error,    setError]    = useState("");

  async function start() {
    setStarting(true);
    setError("");
    // Condition is chosen here, in the browser. The research condition counter is never used.
    const condition = choice === "random" ? randomDemoCondition() : choice;
    const res = await enterDemo(condition);
    if (!res.ok) {
      setError(res.error ?? "The demo is not available right now.");
      setStarting(false);
      return;
    }
    onStarted();
  }

  return (
    <main className="flex-1 flex items-center justify-center px-4 py-16">
      <div className="w-full max-w-xl space-y-8">
        <div className="space-y-2">
          <p className="text-xs font-mono tracking-widest text-zinc-400 uppercase">Demo</p>
          <h1 className="text-2xl font-semibold tracking-tight text-zinc-100">Try the KAIROS demo</h1>
          <p className="text-sm text-zinc-400 leading-relaxed">
            The KAIROS study is <strong className="text-zinc-200">closed</strong> and is no longer
            collecting data. You can still walk through the full participant flow.
          </p>
        </div>

        <ul className="space-y-2 text-sm text-zinc-300 leading-relaxed list-disc list-inside">
          <li><strong className="text-zinc-100">Nothing is saved.</strong> Your answers stay in this browser tab and disappear when you close it.</li>
          <li>Demo sessions are never added to the study data and play no part in it.</li>
          <li>Evidence cards and the reflection question may be generated by an AI model from what you type. Please don&apos;t enter anything personal.</li>
        </ul>

        <fieldset className="space-y-3">
          <legend className="text-xs font-semibold uppercase tracking-widest text-zinc-400">
            When should the reflection question appear?
          </legend>
          {CHOICES.map(c => (
            <label
              key={c.value}
              className={`block cursor-pointer rounded-lg border px-4 py-3 space-y-1 transition-colors ${
                choice === c.value ? "border-zinc-100 bg-zinc-900" : "border-zinc-800 bg-zinc-900 hover:border-zinc-600"
              }`}
            >
              <span className="flex items-center gap-2 text-sm font-medium text-zinc-100">
                <input
                  type="radio"
                  name="demo-condition"
                  value={c.value}
                  checked={choice === c.value}
                  onChange={() => setChoice(c.value)}
                  className="accent-zinc-100"
                />
                {c.label}
              </span>
              <span className="block text-xs text-zinc-400 leading-relaxed">{c.blurb}</span>
            </label>
          ))}
        </fieldset>

        {error && (
          <p className="text-sm text-red-400 bg-zinc-900 border border-red-800 rounded-lg px-4 py-3">{error}</p>
        )}

        <button
          type="button"
          onClick={start}
          disabled={starting}
          className="w-full bg-zinc-100 text-zinc-950 rounded-lg px-6 py-3 font-medium text-sm hover:bg-white transition-colors disabled:opacity-40"
        >
          {starting ? "Starting…" : "Try the demo →"}
        </button>

        <p className="text-xs text-zinc-500 leading-relaxed">
          The paper, preregistration and analysis are at{" "}
          <a href="https://osf.io/nmuk7/" className="underline underline-offset-2 hover:text-zinc-300">osf.io/nmuk7</a>.
        </p>
      </div>
    </main>
  );
}
